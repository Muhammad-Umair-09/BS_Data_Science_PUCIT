.model small
.stack 100h
.386
.DATA
ERR db "INVALID INPUT $"
FORMAT DB 02,08,10,16,'$'
BIN DB 'ENTER INPUT IN BINARY(0-1): $'
OCT DB 'ENTER INPUT IN OCTAL(0-7): $'
DECI DB 'ENTER INPUT IN DECIMAL(0-9) MAX_RANGE(0-255): $'
HEXA DB 'ENTER INPUT IN HEXA_DECIMAL(0-9 AND A-F): $'
OTHER_FORMATS_MSG DB 'OUTPUT IN OTHER FORMATS ARE: $'
.code
main proc
mov ax,@data
mov ds,ax
MOV ES,AX

TAKE_BINARY_INPUT:
MOV AH,09
MOV DX,OFFSET BIN
INT 21H
MOV BL,2
CALL INPUT
CMP DX,1
JE TAKE_OCTAL_INPUT
CALL OUTPUT

TAKE_OCTAL_INPUT:
MOV AH,09
MOV DX,OFFSET OCT
INT 21H
MOV BL,8
CALL INPUT
CMP DX,1
JE TAKE_DECIMAL_INPUT
CALL OUTPUT

TAKE_DECIMAL_INPUT:
MOV AH,09
MOV DX,OFFSET DECI
INT 21H
MOV BL,10
CALL INPUT
CMP DX,1
JE TAKE_HEXA_INPUT
CALL OUTPUT

TAKE_HEXA_INPUT:
MOV AH,09
MOV DX,OFFSET HEXA
INT 21H
MOV BL,16
CALL INPUT
CMP DX,1
JE END_PROGRAM
CALL OUTPUT

END_PROGRAM:
MOV AH,4CH
int 21h

main endp


NEWLINE PROC		;newline
PUSH AX
PUSH DX
MOV AH,02
MOV DL,0DH
INT 21H
MOV DL,0AH
INT 21H
POP DX
POP AX
RET
NEWLINE ENDP

OUTPUT PROC		;OUTPUT PROC
PUSH CX
PUSH DX

PUSH AX
MOV AH,09
MOV DX,OFFSET OTHER_FORMATS_MSG		;OTHER FROMAT MESSAGE 
INT 21H
POP AX
CALL NEWLINE
MOV SI,OFFSET FORMAT
START:
MOV CX,0
MOV DL,[SI]
INC SI
CMP DL,'$'
JZ TERMINATE
CMP BX,DX
JE START
PUSH AX
PUSH BX
MOV BX,DX
CONV_LOOP:
MOV DX,0
DIV BX
PUSH DX
INC CX
CMP AX,0
JNZ CONV_LOOP

MOV AH,02
PRINTING_LOOP:
POP DX
CMP DX,9
JLE DIGIT
ADD DX,7
DIGIT:
ADD DX,30H
INT 21H
DEC CX
JNZ PRINTING_LOOP
POP BX
POP AX
CALL NEWLINE
JMP START

TERMINATE:
POP DX
POP CX
RET
OUTPUT ENDP


INPUT proc		;INPUT PROC
PUSH CX

MOV CX,8		
CMP BL,2
JZ TAKE_INPUT

MOV CX,2
CMP BL,8
JZ TAKE_INPUT

MOV CX,3
CMP BL,10
JZ TAKE_INPUT

MOV CX,2

TAKE_INPUT:
MOV AX,0
MOV DX,0
PUSH AX
AGAIN:
mov ah,01
int 21h
CMP AL,13
JE EXIT
CMP AL,30H
JL ERROR
SUB AL,30H
CMP AL,9
JLE STORE_DATA
SUB AL,7
STORE_DATA:
CMP AL,BL
JGE ERROR
MOV DL,AL
POP AX
MUL BL
ADD AL,DL
PUSH AX
DEC CX
JNZ AGAIN

EXIT:
CALL NEWLINE
MOV DX,0
POP AX
POP CX
RET

ERROR:
CALL NEWLINE
MOV DX,OFFSET ERR
MOV AH,09
INT 21H
MOV DX,1
POP AX
POP CX
CALL NEWLINE
RET
INPUT ENDP

end main