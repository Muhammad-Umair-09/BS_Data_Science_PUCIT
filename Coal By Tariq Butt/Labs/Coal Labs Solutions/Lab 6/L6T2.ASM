.MODEL SMALL
.STACK 100H
.386
.DATA

.CODE

MAIN PROC
MOV AX,@DATA
MOV DS,AX

AGAIN:
MOV AH,01
INT 21H
MOV BL,AL
CMP AL,13
JZ EXIT

CALL NEWLINE

CALL HEXA

CALL NEWLINE
JMP AGAIN

EXIT:
MOV AH,4CH
INT 21H

MAIN ENDP

NEWLINE PROC
MOV AH,02
MOV DL,0DH
INT 21H
MOV DL,0AH
INT 21H
RET
NEWLINE ENDP

HEXA PROC
MOV AH,02
MOV CX,2
BIT:
ROR BL,4
MOV DL,BL
AND DL,0FH
ADD DL,30H
CMP DL,39H
JLE PRINT
ADD DL,7
PRINT:
INT 21H
DEC CX
JNZ BIT

RET

HEXA ENDP

END MAIN
