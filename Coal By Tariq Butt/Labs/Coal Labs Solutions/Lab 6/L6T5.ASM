.MODEL SMALL
.STACK 100H
.386

.DATA

.CODE

MAIN PROC

CALL CIN
MOV BH,BL
CALL NEWLINE
CALL CIN
ADD BL,BH
CALL NEWLINE
JNC OUTPUT
MOV DL,'1'
MOV AH,02
INT 21H

OUTPUT:
CALL BINARY
CALL NEWLINE
CALL HEX

MOV AH,4CH
INT 21H

MAIN ENDP

BINARY PROC
MOV CX,8
MOV AH,02
LOOP1:
ROL BL,1
MOV DL,BL
AND DL,01H
ADD DL,30H
INT 21H
DEC CX
JNZ LOOP1
RET
BINARY ENDP

HEX PROC
MOV CX,2
MOV AH,02
AGAIN:
ROL BL,4
MOV DL,BL
AND DX,000FH

CMP DL,9
JG ADDHEX

ADD DL,30H
JMP PRINT

ADDHEX:
ADD DL,37H
        
PRINT:
INT 21H
DEC CX
JNZ AGAIN
RET
HEX ENDP

NEWLINE PROC
MOV AH,02
MOV DL,0DH
INT 21H
MOV DL,0AH
INT 21H
RET
NEWLINE ENDP

CIN PROC
BEGIN:
MOV CX,8
MOV BL,00
MOV AH,01

AGAIN1:
INT 21H
CMP AL,0DH
JE EXIT
CMP AL,30H
JE NUM
CMP AL,31H
JE NUM
CALL NEWLINE
JMP BEGIN

NUM:
SUB AL,30H
SHL BL,1
OR BL,AL
DEC CX
JNZ AGAIN1

EXIT:
RET
CIN ENDP

END MAIN
        
