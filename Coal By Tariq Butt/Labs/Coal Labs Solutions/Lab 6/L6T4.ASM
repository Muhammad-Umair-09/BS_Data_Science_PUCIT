.MODEL SMALL
.STACK 100H
.386

.DATA

.CODE

MAIN PROC

CALL CIN
CALL NEWLINE
MOV CX,4
MOV AH,02
AGAIN:
ROL BX,4
MOV DX,BX
AND DX,000FH

CMP DX,9
JG ADDHEX

ADD DX,30H
JMP PRINT

ADDHEX:
ADD DX,37H
        
PRINT:
INT 21H
DEC CX
JNZ AGAIN

MOV AH,4CH
INT 21H

MAIN ENDP

NEWLINE PROC
MOV AH,02
MOV DL,0DH
INT 21H
MOV DL,0AH
INT 21H
RET
NEWLINE ENDP

CIN PROC
BEGIN:
MOV CX,16
MOV BX,0000
MOV AH,01

AGAIN1:
INT 21H
CMP AL,0DH
JE EXIT
CMP AL,30H
JE NUM
CMP AL,31H
JE NUM
CALL NEWLINE
JMP BEGIN

NUM:
SUB AL,30H
SHL BX,1
OR BL,AL
DEC CX
JNZ AGAIN1

EXIT:
RET
CIN ENDP

END MAIN
        
