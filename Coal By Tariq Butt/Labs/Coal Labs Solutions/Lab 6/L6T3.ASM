.MODEL SMALL
.STACK 100H
.386
.DATA
.CODE
MAIN PROC

CALL CIN

CALL NEWLINE

;OUTPUT
MOV CX,16
MOV AH,02
AGAIN:
ROL BX,1
MOV DX,BX
AND DX,0001H
ADD DX,30H
INT 21H
DEC CX
JNZ AGAIN

MOV AH,4CH
INT 21H

MAIN ENDP

CIN PROC
BEGIN:
MOV AH,01
MOV BX,0000
MOV CX,4
AGAIN1:
INT 21H
CMP AL,0DH
JZ EXIT
CMP AL,39H
JLE CHECKNUM
CMP AL,65
JGE CHECKCHR
CHR:
SUB AL,37H
JMP ADDDATA
NUM:
SUB AL,30H
ADDDATA:
SHL BX,4
OR BL,AL
DEC CX
JNZ AGAIN1
EXIT:
RET
CHECKCHR:
CMP AL,70
JLE CHR
CALL NEWLINE
JMP BEGIN

CHECKNUM:
CMP AL,30H
JGE NUM
CALL NEWLINE
JMP BEGIN
CIN ENDP

NEWLINE PROC
MOV AH,02
MOV DL,0DH
INT 21H
MOV DL,0AH
INT 21H
RET
NEWLINE ENDP
END MAIN
