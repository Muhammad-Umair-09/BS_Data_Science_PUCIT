.MODEL SMALL
.STACK 100H
.386
.DATA

.CODE

MAIN PROC
MOV AX,@DATA
MOV DS,AX

CALL CIN
MOV BL,AL
CALL NEWLINE
CALL BINARY
CALL NEWLINE
CALL COUNT

MOV AH,4CH
INT 21H

MAIN ENDP

CIN PROC
MOV AH,01
INT 21H
RET
CIN ENDP

NEWLINE PROC
MOV AH,02
MOV DL,0DH
INT 21H
MOV DL,0AH
INT 21H
RET
NEWLINE ENDP

BINARY PROC
MOV CL,8

TILL:
ROL BL,1
JC CARRY
MOV DL,"0"
JMP print

CARRY:
MOV DL,"1"
print:
MOV AH,02
INT 21H
DEC CX
JNZ TILL
RET
BINARY ENDP

COUNT PROC
MOV CX,8
MOV DL,00
AGAIN:
SHL BL,1
JNC EXIT
INC DL
EXIT:
DEC CX
JNZ AGAIN
ADD DL,30H
MOV AH,02
INT 21H
RET
COUNT ENDP

END MAIN
