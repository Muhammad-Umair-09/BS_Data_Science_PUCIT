.MODEL SAMLL
.STACK 100H
.DATA
ARR DB 48,49,50,51,52,53,54,55

.CODE
MAIN PROC
MOV AX,@DATA
MOV DS,AX

MOV CX,8
MOV SI,OFFSET ARR

MOV AH,01H       
INT 21H
SUB AL,'0'

COPY:
ADD [SI],AL
INC SI
DEC CX
JNZ COPY

MOV SI,OFFSET ARR
MOV CX,8
MOV AH,02
AGAIN:
MOV DL,[SI]
INC SI
DEC CX
INT 21H
JNZ AGAIN


MOV AH,4CH
INT 21H

MAIN ENDP
END MAIN
