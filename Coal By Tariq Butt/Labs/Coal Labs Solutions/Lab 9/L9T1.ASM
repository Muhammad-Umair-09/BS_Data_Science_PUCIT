.MODEL SMALL
.STACK 100H
.386
.DATA
GARBAGE DB 140 DUP(00H)
INPUT DB "ENTER ADDRESS IN HEX FFFF: $"
ASCII DB 16 DUP(00H),'$'

.CODE

NEWLINE PROC		;NEW LINE PROC
PUSH AX
PUSH DX
MOV AH,02
MOV DL,0DH
INT 21H
MOV DL,0AH
INT 21H
POP DX
POP AX
RET
NEWLINE ENDP		;NEWLINE ENDP

CIN PROC		;INPUT PROC
PUSH DX
PUSH CX
PUSH AX

LEA DX,INPUT
MOV AH,09
INT 21H

MOV AX,0000
MOV BX,0000
MOV CX, 4       

AGAIN:
MOV AH, 01H    
INT 21H
CMP AL, 13     
JE EXIT

SUB AL,'0'  
CMP AL, 9
JBE STORE_DIGIT 
SUB AL,7	

STORE_DIGIT:
SHL BX, 4     
OR BL, AL    
DEC CX
JNZ AGAIN
EXIT:
POP DX
POP AX
POP CX
MOV CX,0
RET
CIN ENDP		;INPUT ENDP

HEXA8 PROC		;HEX PROC FOR 1 BYTE
PUSH BX
PUSH CX
PUSH AX
PUSH DX
MOV AH,02
MOV CX,2
BIT:
ROL BL,4
MOV DL,BL
AND DL,0FH
ADD DL,30H
CMP DL,39H
JLE PRINT6
ADD DL,7
PRINT6:
INT 21H
DEC CX
JNZ BIT
CALL SPACE
POP DX
POP AX
POP CX
POP BX
RET
HEXA8 ENDP		;1 BYTE HEX ENDP

SPACE PROC		;SPACE PROC
PUSH AX
PUSH DX
XOR AX,AX
XOR DX,DX
MOV AH,02
MOV DL,20H
INT 21H
POP DX
POP AX
RET
SPACE ENDP		;END SPACE PROC

HEXA16 PROC		; HEX PROC FOR 2 BYTES
PUSH AX
PUSH BX
PUSH DX
PUSH CX
MOV AH,02
MOV CX,4
BIT1:
ROL BX,4
MOV DL,BL
AND DL,0FH
ADD DL,30H
CMP DL,39H
JLE PRINT5
ADD DL,7
PRINT5:
INT 21H
DEC CX
JNZ BIT1
POP CX
POP DX
POP BX
POP AX
RET
HEXA16 ENDP		;2 BYTES HEX ENDP

PRINT_ADD PROC		;DS ADDRESS AND OFFSET ADDRESS PRINT AT THE START OF LINE
PUSH AX
PUSH BX
PUSH DX
MOV BX,DS
CALL HEXA16
MOV AH,02
MOV DX,':'
INT 21H
MOV BX,SI
CALL HEXA16
CALL SPACE
POP DX
POP BX
POP AX
RET
PRINT_ADD ENDP		;ADDRESS PROC ENDP

CONVERT PROC		;DUMP DATA PROC
MOV SI,BX
xor bx,bx
MOV CX,8
OUTERLOOP:
PUSH CX
MOV CX,16
MOV DI,OFFSET ASCII
CALL PRINT_ADD
INNERLOOP:
MOV BL,[SI]
MOV [DI],BL
CALL HEXA8
INC SI
INC DI
DEC CX
JNZ INNERLOOP
MOV DX,OFFSET ASCII
MOV AH,09
INT 21H
CALL NEWLINE
POP CX
DEC CX
JNZ OUTERLOOP
RET
CONVERT ENDP		;DUMP PROC ENDP

MAIN PROC		;MAIN PROC
MOV AX,@DATA
MOV DS,AX

MOV BX,OFFSET GARBAGE		;INITIALIZE GARBAGE TO TEST PROGRAM
MOV CX,128
MOV DX,48
L1:
MOV [BX],DX
INC BX
INC DX
DEC CX
JNZ L1

CALL CIN		;CALL INPUT PROC
CALL NEWLINE		
CALL CONVERT		;CALL FUNCTION TO DUMP DATA

MOV AH,4CH		;ENDS PROGRAM
INT 21h

MAIN ENDP
END MAIN
