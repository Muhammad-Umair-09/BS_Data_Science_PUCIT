.MODEL SMALL
.STACK 100H
.386

.DATA
INPUT DB "ENTER INPUT IN HEX 'FFFF': $"
HR DB "HOURS: $"
MN DB "MINUTES: $"
SEC DB "SECONDS: $"

.CODE
NEWLINE PROC		;NEW LINE PROC
PUSH AX
PUSH DX
MOV AH,02
MOV DL,0DH
INT 21H
MOV DL,0AH
INT 21H
POP DX
POP AX
RET
NEWLINE ENDP

CIN PROC
PUSH DX
PUSH CX
PUSH AX

MOV DX,OFFSET INPUT
MOV AH,09
INT 21H

MOV AX,0000
MOV BX,0000
MOV CX, 4       

AGAIN:
MOV AH, 01H    
INT 21H
CMP AL, 13     
JE EXIT

SUB AL, '0'  
CMP AL, 9
JBE STORE_DIGIT 
SUB AL,7	

STORE_DIGIT:
SHL BX, 4     
OR BL, AL    
DEC CX
JNZ AGAIN
EXIT:
POP DX
POP AX
POP CX
MOV CX,0
RET
CIN ENDP


PRINT PROC

MOV AX,BX		;HOUR/MIN/SEC CONVERTION
MOV BX,60
MOV CX,2
L1:
MOV DX,0000
DIV BX
PUSH DX
DEC CX
JNZ L1
PUSH AX
MOV BX,10


MOV DX,0000		;HOURS PRINTING
CALL NEWLINE

MOV DX,OFFSET HR
MOV AH,09
INT 21H

MOV AH,02
MOV DX,0000
POP AX
DIV BX
PUSH DX
MOV DX,AX
ADD DX,30H
MOV AH,02
INT 21H
POP DX
ADD DX,30H
INT 21H			;HOURS PRINTING END


MOV DX,0000		;MINUTES PRINTING
CALL NEWLINE
MOV DX,OFFSET MN
MOV AH,09
INT 21H

MOV AH,02
MOV DX,0000
POP AX
DIV BX
PUSH DX
MOV DX,AX
ADD DX,30H
MOV AH,02
INT 21H
POP DX
ADD DX,30H
INT 21H			;MINUTES PRINTING END


MOV DX,0000		;SECONDS PRINTING
CALL NEWLINE
MOV DX,OFFSET SEC
MOV AH,09
INT 21H

MOV AH,02
MOV DX,0000
POP AX
DIV BX
PUSH DX
MOV DX,AX
ADD DX,30H
MOV AH,02
INT 21H
POP DX
ADD DX,30H
INT 21H			;HOURS PRINTING END

RET
PRINT ENDP

MAIN PROC		;MAIN PROC
MOV AX,@DATA
MOV DS,AX   

CALL CIN
;MOV BX,1234H

CALL PRINT    

MOV AH,4CH
INT 21H

MAIN ENDP		;MEIN END
END MAIN

