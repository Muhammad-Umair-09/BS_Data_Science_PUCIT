.MODEL SMALL
.STACK 100H
.386

.DATA
INPUT DB "ENTER INPUT IN HEX 'FF': $"
HD DB "HALF DOLLARS: $"
Q DB "QUARTERS: $"
D DB "DIMES: $"
N DB "NICKLES: $"
P DB "PENNIES: $"

.CODE
NEWLINE PROC		;NEW LINE PROC
PUSH AX
PUSH DX
MOV AH,02
MOV DL,0DH
INT 21H
MOV DL,0AH
INT 21H
POP DX
POP AX
RET
NEWLINE ENDP

CIN PROC

PUSH CX
PUSH AX
PUSH DX

MOV DX,OFFSET INPUT
MOV AH,09
INT 21H

MOV AX,0000
MOV BX,0000
MOV CX, 2

AGAIN:
MOV AH, 01H    
INT 21H
CMP AL, 13     
JE EXIT

SUB AL, '0'  
CMP AL, 9
JBE STORE_DIGIT 
SUB AL,7	

STORE_DIGIT:
SHL BX, 4     
OR BL, AL    
DEC CX
JNZ AGAIN
EXIT:
POP DX
POP AX
POP CX
RET
CIN ENDP		;INPUT PROC END


PRINT PROC		;NUMBER PRINTING PROC
PUSH AX
ADD DX,'0'
MOV AH,02
INT 21H
POP AX
MOV DX,0
RET
PRINT ENDP

PRINT_STR PROC		;STRING PRINTING PROC
PUSH AX
MOV AH,09
INT 21H
POP AX
RET
PRINT_STR ENDP

CONVERT PROC		;CONVERTION PROC
MOV AX,BX		
MOV DX,0000



MOV BX,50		;HALF DOLLAR
DIV BX
CALL NEWLINE
PUSH DX
MOV DX,OFFSET HD
CALL PRINT_STR
POP DX
XCHG AX,DX
CALL PRINT

MOV BX,25		;QUARTERS
DIV BX
CALL NEWLINE
PUSH DX
MOV DX,OFFSET Q
CALL PRINT_STR
POP DX
XCHG AX,DX
CALL PRINT

MOV BX,10		;DIMES
DIV BX
CALL NEWLINE
PUSH DX
MOV DX,OFFSET D
CALL PRINT_STR
POP DX
XCHG AX,DX
CALL PRINT

MOV BX,5		;NICKLES
DIV BX
CALL NEWLINE
PUSH DX
MOV DX,OFFSET N
CALL PRINT_STR
POP DX
XCHG AX,DX
CALL PRINT

CALL NEWLINE            ;PENNIES
PUSH DX
MOV DX,OFFSET P
CALL PRINT_STR
POP DX
MOV DX,AX
CALL PRINT

RET
CONVERT ENDP

MAIN PROC		;MAIN PROC
MOV AX,@DATA
MOV DS,AX   

CALL CIN

CALL CONVERT

MOV AH,4CH
INT 21H

MAIN ENDP		;MEIN END
END MAIN

