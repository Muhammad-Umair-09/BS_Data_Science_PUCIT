DIV16 ENDP

MULBYPOW PROC
PUSH BX
PUSH DX
SUB DX,30H
MOV CL,DL
SHL BX,CL
CALL HEXA16
POP DX
POP BX
RET
MULBYPOW ENDP

DIVBYPOW PROC
PUSH BX
PUSH DX
SUB DX,30H
MOV CL,DL
SHR BX,CL
CALL HEXA16
POP DX
POP BX
RET
DIVBYPOW ENDP

BINARY8 PROC
CALL NEWLINE
PUSH BX
MOV AH,09
MOV DX,OFFSET NEWNUM
INT 21H
MOV CL,8
TILL1:
ROL BL,1
JC CARRY1
MOV DL,"0"
JMP print4

CARRY1:
MOV DL,"1"
print4:
MOV AH,02
INT 21H
DEC CX
JNZ TILL1
POP BX
RET
BINARY8 ENDP

BINARY16 PROC
CALL NEWLINE
PUSH BX
MOV AH,09
MOV DX,OFFSET NEWNUM
INT 21H
MOV CL,16
TILL:
ROL BX,1
JC CARRY2
MOV DL,"0"
JMP print3

CARRY2:
MOV DL,"1"
print3:
MOV AH,02
INT 21H
DEC CX
JNZ TILL
POP BX
RET
BINARY16 ENDP

HEXA16 PROC
CALL NEWLINE
PUSH BX
MOV AH,09
MOV DX,OFFSET NEWNUM
INT 21H
MOV AH,02
MOV CX,4
BIT1:
ROL BX,4
MOV DL,BL
AND DL,0FH
ADD DL,30H
CMP DL,39H
JLE PRINT5
ADD DL,7
PRINT5:
INT 21H
DEC CX
JNZ BIT1
POP BX
RET
HEXA16 ENDP

HEXA8 PROC
CALL NEWLINE
PUSH BX
MOV AH,09
MOV DX,OFFSET NEWNUM
INT 21H
MOV AH,02
MOV CX,2
BIT:
ROL BL,4
MOV DL,BL
AND DL,0FH
ADD DL,30H
CMP DL,39H
JLE PRINT6
ADD DL,7
PRINT6:
INT 21H
DEC CX
JNZ BIT
POP BX
RET
HEXA8 ENDP

MUL10 PROC
PUSH BX
MOV AX,BX
SUB AX,30H
MOV CX,10
MUL CX
MOV BX,AX
CALL HEXA16
POP BX
RET
MUL10 ENDP

MUL13 PROC
PUSH BX
MOV AX,BX
SUB AX,30H
MOV CX,13
MUL CX
MOV BX,AX
CALL HEXA16
POP BX
RET
MUL13 ENDP

END MAIN
