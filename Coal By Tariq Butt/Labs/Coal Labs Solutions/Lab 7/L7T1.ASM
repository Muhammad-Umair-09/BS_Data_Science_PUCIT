.MODEL SMALL
.STACK 100H
.386
.DATA
EV DB 'EVEN$'
OD DB 'ODD$'
SML DB 'SMALL$'
CAP DB 'CAPITAL$'
NEWNUM DB 'NEW NUMBER IS $'
.CODE
MAIN PROC
MOV AX,@DATA
MOV DS,AX

PUSH BX
CALL CIN
MOV BL,AL
CALL EVENODD
POP BX

PUSH BX
CALL CIN
MOV BL,AL
CALL CAPSML
POP BX

PUSH BX
CALL CIN
MOV BL,AL
CALL MUL2
POP BX

PUSH BX
CALL CIN
MOV BL,AL
CALL MUL4
POP BX

PUSH BX
CALL CIN
MOV BL,AL
CALL MUL8
POP BX

PUSH BX
CALL CIN
MOV BL,AL
CALL MUL16
POP BX

PUSH BX
CALL CIN
MOV BL,AL
CALL DIV2
POP BX

PUSH BX
CALL CIN
MOV BL,AL
CALL DIV4
POP BX

PUSH BX
CALL CIN
MOV BL,AL
CALL DIV8
POP BX

PUSH BX
CALL CIN
MOV BL,AL
CALL DIV16
POP BX

PUSH BX
PUSH DX
CALL CIN
MOV BL,AL
CALL CIN
MOV DL,AL
CALL MULBYPOW
POP DX
POP BX

PUSH BX
PUSH DX
CALL CIN
MOV BL,AL
CALL CIN
MOV DL,AL
CALL DIVBYPOW
POP DX
POP BX

PUSH BX
CALL CIN
MOV BL,AL
CALL BINARY8
POP BX

PUSH BX
CALL CIN
MOV BL,AL
CALL HEXA8
POP BX

PUSH BX
CALL CIN
MOV BL,AL
CALL BINARY16
POP BX

PUSH BX
CALL CIN
MOV BL,AL
CALL HEXA16
POP BX

PUSH BX
CALL CIN
MOV BL,AL
CALL MUL10
POP BX

PUSH BX
CALL CIN
MOV BL,AL
CALL MUL13
POP BX

MOV AH,4CH
INT 21H
          
MAIN ENDP

CIN PROC
CALL NEWLINE
MOV AH,01
INT 21H
RET
CIN ENDP


NEWLINE PROC
PUSH BX
PUSH DX
MOV AH,02
MOV DL,0DH
INT 21H
MOV DL,0AH
INT 21H
POP DX
POP BX
RET
NEWLINE ENDP

EVENODD PROC
CALL NEWLINE
PUSH BX
AND BX,0001H
CMP BX,1
JNZ EVN
MOV DX,OFFSET OD
JMP PRINT1
EVN:
MOV DX,OFFSET EV
PRINT1:
MOV AH,09
INT 21H
POP BX
RET
EVENODD ENDP

CAPSML PROC
CALL NEWLINE
PUSH BX
PUSH DX
CMP BL,97
JGE SM
MOV DX,OFFSET CAP
JMP PRINT2
SM:
MOV DX,OFFSET SML
PRINT2:
MOV AH,09
INT 21H
POP DX
POP BX
RET
CAPSML ENDP

MUL2 PROC
PUSH DX
PUSH BX
SHL BX,1
CALL HEXA16
POP BX
POP DX
RET
MUL2 ENDP

MUL4 PROC
PUSH DX
PUSH BX
SHL BX,2
CALL HEXA16
POP BX
POP DX
RET
MUL4 ENDP

MUL8 PROC
