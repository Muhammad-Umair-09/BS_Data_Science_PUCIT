.MODEL SMALL
.STACK 100H
.386
.DATA
	INPUT DB "ENTER ADDRESS IN HEX FFFF: $"
	ERR DB 'INVALID RANGE OR INPUT! $'
.CODE

NEWLINE PROC		;NEW LINE PROC
	PUSH AX
	PUSH DX
	MOV AH,02
	MOV DL,0DH
	INT 21H
	MOV DL,0AH
	INT 21H
	POP DX
	POP AX
RET
NEWLINE ENDP		;NEWLINE ENDP

CIN PROC		;INPUT PROC
	PUSH CX
	PUSH AX

	MOV SI,0
	MOV AX,0
	MOV BX,0
	MOV CX,0

	MOV DI,0080H
	MOV CL,ES:[DI]
	DEC CX
	MOV DI,0082H    

	AGAIN:
	MOV AL,ES:[DI]
	CMP AL,':'
		JE STORE_SEG
	CMP AL,' '
		JE STORE_STARTING_ADDR
	CMP AL, 30H     
		JL ERROR
	CMP AL,39H
		JBE STORE_DIGIT  
	CMP AL,'A'
		JB ERROR
	CMP AL,'F'
		JBE STORE_HEX
	CMP AL,'a'
		JB ERROR
	CMP AL,'f'
		JBE STORE_SMALL_HEX

	JMP ERROR

	STORE_SMALL_HEX:
	SUB AL,30

	STORE_HEX:
	SUB AL,7	

	STORE_DIGIT:
	SUB AL,'0'
	SHL BX, 4     
	OR BL, AL 
	
	BACK_TO_LOOP:
	INC DI   
	DEC CX
	JNZ AGAIN
	
	JMP EXIT

	ERROR:
	MOV DX,OFFSET ERR
	MOV AH,09
	INT 21H
	JMP TERMINATE

	EXIT:
	POP AX
	POP CX

	CMP SI,0
	JE MOVE_STARTING_ADDR_TO_SI
	CMP SI,BX
	JG ERROR
RET
	MOVE_STARTING_ADDR_TO_SI:
	MOV SI,BX
	ADD BX,128
RET

	STORE_SEG:
	MOV DS,BX
	MOV BX,0
		JMP BACK_TO_LOOP

	STORE_STARTING_ADDR:
	MOV SI,BX
	MOV BX,0
	JMP BACK_TO_LOOP

CIN ENDP		;INPUT ENDP

HEXA8 PROC		;HEX PROC FOR 1 BYTE
	PUSH BX
	PUSH CX
	PUSH AX
	PUSH DX
	MOV AH,02
	MOV CX,2
	BIT:
	ROL BL,4
	MOV DL,BL
	AND DL,0FH
	ADD DL,30H
	CMP DL,39H
		JLE PRINT6
	ADD DL,7
	PRINT6:
	INT 21H
	DEC CX
	JNZ BIT
CALL SPACE
	POP DX
	POP AX
	POP CX
	POP BX
RET
HEXA8 ENDP		;1 BYTE HEX ENDP

SPACE PROC		;SPACE PROC
	PUSH AX
	PUSH DX
	XOR AX,AX
	XOR DX,DX
	MOV AH,02
	MOV DL,20H
	INT 21H
	POP DX
	POP AX
RET
SPACE ENDP		;END SPACE PROC

HEXA16 PROC		; HEX PROC FOR 2 BYTES
	PUSH AX
	PUSH BX
	PUSH DX
	PUSH CX
	MOV AH,02
	MOV CX,4
	BIT1:
	ROL BX,4
	MOV DL,BL
	AND DL,0FH
	ADD DL,30H
	CMP DL,39H
		JLE PRINT5
	ADD DL,7
	PRINT5:
	INT 21H
	DEC CX
		JNZ BIT1
	POP CX
	POP DX
	POP BX
	POP AX
RET
HEXA16 ENDP		;2 BYTES HEX ENDP

PRINT_ADD PROC		;DS ADDRESS AND OFFSET ADDRESS PRINT AT THE START OF LINE
	PUSH AX
	PUSH BX
	PUSH DX
	MOV BX,DS
CALL HEXA16
	MOV AH,02
	MOV DX,':'
	INT 21H
	MOV BX,SI
CALL HEXA16

CALL SPACE
	POP DX
	POP BX
	POP AX
RET
PRINT_ADD ENDP		;ADDRESS PROC ENDP

CONVERT PROC		;DUMP DATA PROC
	MOV DI,BX

	START_OF_CONV:
	MOV CX,0
CALL PRINT_ADD
	INNERLOOP:
	MOV BL,[SI]
	CALL HEXA8
	INC SI
	INC CX
	CMP SI,DI
		JE ASCII_BLOCK
	CMP CX,16
		JNZ INNERLOOP

	ASCII_BLOCK:
	SUB SI,CX
	MOV AH,02
	ASCII_PRINT:
	MOV DL,[SI]
	INT 21H
	INC SI
	DEC CX
		JNZ ASCII_PRINT
CALL NEWLINE
	CMP SI,DI
		JE END_OF_CONV
	JMP START_OF_CONV

END_OF_CONV:
RET
CONVERT ENDP		;DUMP PROC ENDP

MAIN PROC		;MAIN PROC
MOV AX,@DATA
MOV DS,AX

CALL CIN		;CALL INPUT PROC
CALL NEWLINE		

CALL CONVERT		;CALL FUNCTION TO DUMP DATA

TERMINATE:
MOV AH,4CH		;ENDS PROGRAM
INT 21h

MAIN ENDP
END MAIN
