.MODEL SMALL
.STACK 100H
.DATA
INPUT_STRING DB 100H DUP('$')

OUTPUT_STR DB 'ENTERED STRING IS: $'
.CODE
MAIN PROC
MOV AX,@DATA
MOV DS,AX
MOV ES,AX

MOV DI,OFFSET INPUT_STRING
MOV CX,100H
MOV AH,01
INPUT_LOOP:
	INT 21H
	CMP AL,13
	JE EXIT
	STOSB
	DEC CX
JNZ INPUT_LOOP

EXIT:
MOV AH,09
MOV DX,OFFSET OUTPUT_STR
INT 21H

MOV DX,OFFSET INPUT_STRING
INT 21H
	
MOV AH,4CH
INT 21H
MAIN ENDP

END MAIN